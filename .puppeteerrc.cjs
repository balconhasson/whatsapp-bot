const { join } = require('path');

/**
 * Pin Puppeteer's browser cache to a project-local directory instead of the
 * default `$HOME/.cache/puppeteer`. On Railway/Nixpacks, files written to the
 * home cache during the build phase are not reliably carried over into the
 * runtime container, which caused "Browser was not found at the configured
 * executablePath" even though `npx puppeteer browsers install chrome`
 * succeeded during build. Keeping the download inside the project directory
 * guarantees it's part of the same build output that ships to runtime.
 *
 * This directory is regenerated by the `build` script on every deploy and
 * is gitignored - it should never be committed.
 */
module.exports = {
    cacheDirectory: join(__dirname, '.cache', 'puppeteer'),
};
